    static func toned(_ base: String, _ tone: SkinTone) -> String {
        let modifier = tone.rawValue
        guard let scalar = base.unicodeScalars.first else { return base }
        let head = String(scalar)
        let tail = base.unicodeScalars.dropFirst()
        var rebuilt = head + modifier
        for s in tail {
            if s == "\u{FE0F}" { continue }
            rebuilt.unicodeScalars.append(s)
        }
        return rebuilt
    }

    static func search(_ query: String) -> [String] {
        let q = query.lowercased().trimmingCharacters(in: .whitespacesAndNewlines)
        guard !q.isEmpty else { return [] }
        var seen = Set<String>()
        var results: [String] = []
        for (emoji, terms) in keywords {
            if terms.contains(where: { $0.contains(q) }) && seen.insert(emoji).inserted {
                results.append(emoji)
            }
        }
        return results
    }
